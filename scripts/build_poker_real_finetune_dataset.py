#!/usr/bin/env python3
"""Build an auditable real-fixture plus synthetic YOLO fine-tuning dataset.

The only real annotations are the two manually reviewed complete corner marks
per fixture in MANUAL_BOXES_PX.  Model predictions are never read or used.
"""

from __future__ import annotations

import argparse
import json
import random
import shutil
from pathlib import Path

import cv2
import numpy as np


# xyxy pixels in the original 420x594 fixture coordinate system. Each rectangle
# covers one full printed rank/letter plus suit corner mark. Coordinates were
# manually reviewed against the source image, not generated by a detector.
MANUAL_BOXES_PX: dict[str, list[tuple[float, float, float, float]]] = {
    "poker_real_1.png": [(151, 42, 220, 88), (201, 182, 268, 228)],
    "poker_real_2.png": [(57, 107, 99, 151), (286, 207, 323, 251)],
    "poker_real_3.png": [(95, 142, 126, 184), (275, 191, 308, 236)],
    "poker_real_4.png": [(304, 156, 340, 198), (108, 302, 147, 337)],
    "poker_real_5.png": [(213, 151, 249, 200), (103, 354, 146, 397)],
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--fixtures", type=Path, default=Path("tests/fixtures"))
    parser.add_argument("--synthetic", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--train-augmentations", type=int, default=48)
    parser.add_argument("--val-augmentations", type=int, default=12)
    parser.add_argument("--seed", type=int, default=260804)
    return parser.parse_args()


def yolo_lines(boxes: np.ndarray, width: int, height: int) -> str:
    lines = []
    for x1, y1, x2, y2 in boxes:
        center_x = (x1 + x2) / (2.0 * width)
        center_y = (y1 + y2) / (2.0 * height)
        box_w = (x2 - x1) / width
        box_h = (y2 - y1) / height
        lines.append(f"0 {center_x:.6f} {center_y:.6f} {box_w:.6f} {box_h:.6f}")
    return "\n".join(lines) + "\n"


def copy_pair(image: Path, label: Path, image_dir: Path, label_dir: Path, name: str) -> None:
    shutil.copy2(image, image_dir / f"{name}{image.suffix.lower()}")
    shutil.copy2(label, label_dir / f"{name}.txt")


def transform(image: np.ndarray, boxes: np.ndarray, rng: random.Random) -> tuple[np.ndarray, np.ndarray]:
    height, width = image.shape[:2]
    src = np.float32([[0, 0], [width - 1, 0], [width - 1, height - 1], [0, height - 1]])
    jitter = np.float32([[rng.uniform(-7, 7), rng.uniform(-9, 9)] for _ in range(4)])
    homography = cv2.getPerspectiveTransform(src, src + jitter)
    angle = rng.uniform(-13.0, 13.0)
    affine = cv2.getRotationMatrix2D((width / 2.0, height / 2.0), angle, rng.uniform(0.94, 1.05))
    affine_h = np.vstack((affine, [0.0, 0.0, 1.0])).astype(np.float32)
    matrix = affine_h @ homography
    augmented = cv2.warpPerspective(image, matrix, (width, height), flags=cv2.INTER_LINEAR, borderMode=cv2.BORDER_REFLECT_101)
    quadrilaterals = []
    for x1, y1, x2, y2 in boxes:
        quadrilaterals.append([[x1, y1], [x2, y1], [x2, y2], [x1, y2]])
    transformed = cv2.perspectiveTransform(np.asarray(quadrilaterals, dtype=np.float32), matrix)
    new_boxes = np.column_stack((transformed.min(axis=1), transformed.max(axis=1)))
    new_boxes = np.column_stack((new_boxes[:, 0], new_boxes[:, 1], new_boxes[:, 2], new_boxes[:, 3]))
    new_boxes[:, [0, 2]] = np.clip(new_boxes[:, [0, 2]], 0, width - 1)
    new_boxes[:, [1, 3]] = np.clip(new_boxes[:, [1, 3]], 0, height - 1)
    gain = rng.uniform(0.75, 1.26)
    bias = rng.uniform(-20, 20)
    augmented = np.clip(augmented.astype(np.float32) * gain + bias, 0, 255).astype(np.uint8)
    if rng.random() < 0.65:
        augmented = cv2.GaussianBlur(augmented, (0, 0), rng.uniform(0.15, 0.9))
    if rng.random() < 0.55:
        noise = np.random.default_rng(rng.randrange(2**32)).normal(0, rng.uniform(1.0, 3.5), augmented.shape)
        augmented = np.clip(augmented.astype(np.float32) + noise, 0, 255).astype(np.uint8)
    return augmented, new_boxes


def write_augments(
    fixture_dir: Path,
    count: int,
    split: str,
    image_dir: Path,
    label_dir: Path,
    audit_dir: Path,
    seed: int,
) -> int:
    images_written = 0
    for source_index, (filename, boxes) in enumerate(MANUAL_BOXES_PX.items()):
        source = fixture_dir / filename
        image = cv2.imread(str(source))
        if image is None:
            raise SystemExit(f"unreadable fixture: {source}")
        manual_boxes = np.asarray(boxes, dtype=np.float32)
        if split == "audit":
            shutil.copy2(source, audit_dir / filename)
            (audit_dir / f"{source.stem}.txt").write_text(yolo_lines(manual_boxes, image.shape[1], image.shape[0]), encoding="ascii")
            overlay = image.copy()
            for x1, y1, x2, y2 in manual_boxes.astype(int):
                cv2.rectangle(overlay, (x1, y1), (x2, y2), (0, 255, 255), 1)
            cv2.imwrite(str(audit_dir / f"{source.stem}_review.png"), overlay)
            continue
        for index in range(count):
            augmented, transformed_boxes = transform(image, manual_boxes, random.Random(seed + source_index * 10_000 + index))
            name = f"real_{source.stem}_{index:03d}"
            cv2.imwrite(str(image_dir / f"{name}.jpg"), augmented, [cv2.IMWRITE_JPEG_QUALITY, 92])
            (label_dir / f"{name}.txt").write_text(yolo_lines(transformed_boxes, augmented.shape[1], augmented.shape[0]), encoding="ascii")
            images_written += 1
    return images_written


def main() -> None:
    args = parse_args()
    if args.output.exists():
        raise SystemExit(f"refusing to overwrite existing dataset: {args.output}")
    fixture_dir = args.fixtures.resolve()
    synthetic = args.synthetic.resolve()
    if not (synthetic / "data.yaml").is_file():
        raise SystemExit(f"missing synthetic data.yaml: {synthetic / 'data.yaml'}")
    for filename in MANUAL_BOXES_PX:
        if not (fixture_dir / filename).is_file():
            raise SystemExit(f"missing expected fixture: {fixture_dir / filename}")
    args.output.mkdir(parents=True)
    audit_dir = args.output / "manual_audit_sources"
    audit_dir.mkdir()
    write_augments(fixture_dir, 0, "audit", audit_dir, audit_dir, audit_dir, args.seed)
    statistics: dict[str, dict[str, int]] = {}
    for split in ("train", "val", "test"):
        image_dir = args.output / "images" / split
        label_dir = args.output / "labels" / split
        image_dir.mkdir(parents=True)
        label_dir.mkdir(parents=True)
        source_image_dir = synthetic / "images" / split
        source_label_dir = synthetic / "labels" / split
        copied = 0
        for image in sorted(source_image_dir.glob("*.jpg")):
            copy_pair(image, source_label_dir / f"{image.stem}.txt", image_dir, label_dir, f"synth_{image.stem}")
            copied += 1
        real_count = 0
        if split == "train":
            real_count = write_augments(fixture_dir, args.train_augmentations, split, image_dir, label_dir, audit_dir, args.seed)
        elif split == "val":
            real_count = write_augments(fixture_dir, args.val_augmentations, split, image_dir, label_dir, audit_dir, args.seed + 5_000_000)
        statistics[split] = {"synthetic_images": copied, "real_augmented_images": real_count, "total_images": copied + real_count}
    root = args.output.resolve().as_posix()
    (args.output / "data.yaml").write_text(
        f"path: {root}\ntrain: images/train\nval: images/val\ntest: images/test\nnames:\n  0: corner_mark\n",
        encoding="ascii",
    )
    lineage = {
        "manual_boxes_px": MANUAL_BOXES_PX,
        "source_fixtures": str(fixture_dir),
        "synthetic_source": str(synthetic),
        "augmentation": "global perspective, rotation, scale, gain, bias, blur, noise; no horizontal or vertical mirror",
        "warning": "All real-derived train and val images originate from five fixtures. Validation is source-overlapping and is not an independent real-world metric.",
        "statistics": statistics,
    }
    (args.output / "lineage.json").write_text(json.dumps(lineage, indent=2), encoding="ascii")
    print(json.dumps(lineage, indent=2))


if __name__ == "__main__":
    main()
